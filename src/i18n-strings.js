/** Looks up a string in a specific language, regardless of the app's current
 * display language. Used for text that always needs to be one language no
 * matter what the staff member has the interface set to - e.g. the WhatsApp
 * message sent to a parent, which should stay Arabic even if a staff member
 * is using the app in English. */
export function translate(lang, key, params = {}) {
  const dict = STRINGS[lang] || STRINGS.en;
  const entry = dict[key] ?? STRINGS.en[key] ?? key;
  return typeof entry === 'function' ? entry(params) : entry;
}
